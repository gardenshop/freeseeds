CREATE TRIGGER guard_incident_fulfillment_audit
BEFORE INSERT ON audit_log
WHEN NEW.entity_type='ORDER'
  AND NEW.entity_id IN (SELECT id FROM orders WHERE order_number='FS-261019-000001')
  AND NEW.action IN ('ORDER_STATE_TRANSITIONED','ORDER_CONFIRMED','ORDER_TRACKING_ASSIGNED')
BEGIN
  SELECT RAISE(ABORT, 'FULFILLMENT_HOLD_INCIDENT_REVIEW_REQUIRED');
END;
